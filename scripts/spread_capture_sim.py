"""
Spread Capture Strategy Simulator

Tests the continuous velocity market maker (spread_capture.py) using real-time data.
Records hypothetical trading activity WITHOUT placing real orders.

Key Differences from calc_maker_velocity_sim.py:
- Continuous two-sided quoting (vs sequential entry→hedge)
- Grid orders at multiple price levels
- Inventory management with 10% max imbalance
- Velocity-based quote ADJUSTMENT (not gating)

Expected Results:
- Cycles/hour: 50-100 (vs 5.6 with old velocity gating)
- Fill rate: 80%+ (vs 12.7% with old approach)
- Profit/hour: $20-40 (vs $3.22 with old approach)

Usage:
    python scripts/spread_capture_sim.py --hours 2 --output research/
    python scripts/spread_capture_sim.py --hours 0.1  # Quick 6-min test
"""

